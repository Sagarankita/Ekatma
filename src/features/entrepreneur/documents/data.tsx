import React from 'react';
import { findBusinessEntity } from '../identity/catalog';

export type DocReqState = 'Required' | 'Conditional' | 'Not Required';
export type DocAvailState = 'Missing' | 'Uploaded' | 'Processing' | 'Available';
export type DocVerifState =
  | 'Self-declared'
  | 'User-confirmed'
  | 'System-verified'
  | 'Department-verified'
  | 'Needs Verification'
  | 'Invalid'
  | 'Government-issued';
export type DocValidity = 'Valid' | 'Expired' | 'Not Applicable';
export type DocReuse = 'Reusable' | 'Service-specific';
export type DocDependency =
  | 'Available now'
  | 'Generated by prerequisite approval'
  | 'Blocked until prerequisite'
  | 'Inspection-stage only'
  | 'Unlocks downstream services';

export interface ExtractedInfo {
  fields: { label: string; value: string; match?: boolean }[];
  verificationState: string;
  reviewRequired: boolean;
  summary?: string;
}

export interface CertificateInfo {
  certNumber: string;
  authority: string;
  issueDate: string;
  validUntil: string;
  signatoryName: string;
  designation: string;
  qrPayload: string;
  conditions: string[];
}

export interface DocRecord {
  id: string;
  name: string;
  category: string;
  issueDate: string;
  expiryDate: string;
  source: string;
  requirement: DocReqState;
  availability: DocAvailState;
  verification: DocVerifState;
  validity: DocValidity;
  reuse: DocReuse;
  dependency: DocDependency;
  usedBy: { dept: string; service: string; requirement: string }[];
  version: number;
  description: string;
  whyRequired: string;
  whatItContains: string;
  grRule: string | null;
  grClause: string | null;
  grEffective: string | null;
  whereObtained: string;
  versionHistory: { version: number; uploaded: string; verification: string }[];
  triggeringCondition?: string;
  extractedData?: ExtractedInfo;
  certificateData?: CertificateInfo;
}

