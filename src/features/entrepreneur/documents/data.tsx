export function findDocumentById(id: string): DocRecord | undefined {
  return EKATMA_DOCS.find(doc => doc.id === id);
}

export function findDocumentForBusiness(businessId: string, documentId: string): DocRecord | undefined {
  if (!findBusinessEntity('document', businessId, documentId)) return undefined;
  return findDocumentById(documentId);
}

export function listDocumentsForBusiness(businessId: string): DocRecord[] {
  return EKATMA_DOCS.filter(doc => Boolean(findBusinessEntity('document', businessId, doc.id)));
}

